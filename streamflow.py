import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

# ChatGPT helped create the shear diagram using the given equations.
# The loop calculates shear forces at each position along the beam.

L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

x = np.linspace(0, L, 500)
V = np.zeros_like(x)

# Calculate shear forces for each section of the beam.
for i in range(len(x)):
    if x[i] < 2:
        V[i] = RA - (q1 * x[i])
    elif x[i] < 4:
        V[i] = RA - (q1 * 2) - P1
    else:
        V[i] = RA - (q1 * 2) - P1 + RB - (q2 * (x[i] - 4))

# Plot the shear diagram and shade the area.
plt.plot(x, V, color="tab:blue")
plt.fill_between(x, V, 0, color="lightblue")

plt.title("Shear Diagram")
plt.xlabel("x (ft)")
plt.ylabel("V (lb)")
plt.axhline(0, color="black", linewidth=1)

plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

# ChatGPT helped create the moment diagram using the given equations.
# The loop calculates the moment at each point along the beam.

L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

x = np.linspace(0, L, 500)
M = np.zeros_like(x)

# Calculate moment for each section of the beam.
for i in range(len(x)):
    if x[i] < 2:
        M[i] = (RA * x[i]) - (q1 * x[i]**2 / 2)
    elif x[i] < 4:
        M[i] = (RA * x[i]) - (q1 * 2 * (x[i] - 1)) - (P1 * (x[i] - 2))
    else:
        M[i] = (RA * x[i]) - (q1 * 2 * (x[i] - 1)) - (P1 * (x[i] - 2)) + (RB * (x[i] - 4)) - (q2 * (x[i] - 4)**2 / 2)

# Plot the moment diagram and fill the area.
plt.plot(x, M, color="red")
plt.fill_between(x, M, 0, color="lightcoral")

plt.title("Moment Diagram")
plt.xlabel("x (ft)")
plt.ylabel("M (lb-ft)")
plt.axhline(0, color="black", linewidth=1)

plt.show()

